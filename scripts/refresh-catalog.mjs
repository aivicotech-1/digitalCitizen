import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const details = JSON.parse(await readFile(path.join(root, 'catalog-details.json'), 'utf8'));
const activities = [];
for (const grade of [2, 3, 4, 5]) {
  const relativeDirectory = `Grade ${grade}/Activities`;
  const directory = path.join(root, relativeDirectory);
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.isFile() || !/\.html?$/i.test(entry.name)) continue;
    const name = entry.name.replace(/\.html?$/i, '');
    const html = await readFile(path.join(directory, entry.name), 'utf8');
    if (!/<html[\s>]/i.test(html)) throw new Error(`Not an HTML document: ${relativeDirectory}/${entry.name}`);
    const detail = details[name] || { description: `Explore ${name} in this Grade ${grade} activity.`, topic: 'Digital citizenship', type: 'Activity', art: 'explore', color: '#dce5e9', order: 100 };
    activities.push({ id: `${grade}-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-$/, '')}`, grade, title: name, ...detail, path: `${relativeDirectory}/${entry.name}` });
  }
}
activities.sort((a, b) => a.grade - b.grade || a.order - b.order || a.title.localeCompare(b.title));
if (new Set(activities.map(activity => activity.id)).size !== activities.length) throw new Error('Activity IDs must be unique. Rename conflicting files.');
await writeFile(path.join(root, 'activities.js'), `// Generated by node scripts/refresh-catalog.mjs. Edit catalog-details.json for descriptions.\nwindow.DIGITAL_CITIZEN_ACTIVITIES = ${JSON.stringify(activities, null, 2)};\n`);
console.log(`Catalogue refreshed: ${activities.length} activities. ${[2, 3, 4, 5].map(grade => `Grade ${grade}: ${activities.filter(activity => activity.grade === grade).length}`).join(' | ')}`);
